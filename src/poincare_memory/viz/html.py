def render_html(
    memory: Memory, title: str | None = None, at_time: datetime | None = None, layout: str = "auto"
) -> str:
    data = to_dict(memory, at_time, layout=layout)
    payload = json.dumps(data).replace("</", "<\\/")
    return _TEMPLATE.replace("__TITLE__", title or "poincare-memory inspector").replace(
        "__DATA__", payload
    )
